/** Saved state of the Slaughter Pit (overworld data storage, there is only one pit per world). */
class PitState(
    var defeated: Boolean = false,
    var kills: Int = 0,
    val playerKills: MutableMap<UUID, Int> = HashMap(),
    /** Arena blocks the fight changed (gate, labyrinth walls, smashed pillars); restored from the design. */
    val changed: MutableSet<Long> = HashSet(),
) : PersistentState() {
    companion object {
        val CODEC: Codec<PitState> = RecordCodecBuilder.create { i ->
            i.group(
                Codec.BOOL.optionalFieldOf("defeated", false).forGetter { it.defeated },
                Codec.INT.optionalFieldOf("kills", 0).forGetter { it.kills },
                Codec.unboundedMap(Uuids.STRING_CODEC, Codec.INT).optionalFieldOf("player_kills", emptyMap()).forGetter { it.playerKills },
                Codec.LONG.listOf().optionalFieldOf("changed", emptyList()).forGetter { it.changed.toList() },
            ).apply(i) { d, k, m, c -> PitState(d, k, HashMap(m), HashSet(c)) }
        }
        val TYPE = PersistentStateType("hha_blood_slaughter_pit", { PitState() }, CODEC, null)
    }
}

/**
 * Everything about the arena blocks at runtime: positions, protection (no breaking/placing/explosions),
 * temporary changes of the fight (portcullis, rising labyrinth walls, pillars smashed by the Minotaur) that
 * are always restored exactly from [HeartVaultPiece.design], and the upgrade of arenas generated by older
 * versions of the mod (rebuilt in slices over a few seconds).
 */
object PitArena {

    fun state(server: MinecraftServer): PitState = server.overworld.persistentStateManager.getOrCreate(PitState.TYPE)

    fun center(): BlockPos? = HollowsRegion.center()

    /** World position of an offset from the centre block (dy 0 = floor level), x/z at block centres for whole numbers + 0.5. */
    fun at(dx: Double, dy: Double, dz: Double): Vec3d {
        val c = center() ?: return Vec3d.ZERO
        return Vec3d(c.x + dx, HeartVaultPiece.FLOOR + dy, c.z + dz)
    }

    fun mid(): Vec3d = at(0.5, 0.0, 0.5)

    fun inDome(pos: Vec3d): Boolean {
        val c = center() ?: return false
        val dx = pos.x - (c.x + 0.5)
        val dz = pos.z - (c.z + 0.5)
        val dy = pos.y - HeartVaultPiece.FLOOR
        return dy > -4 && dy < HeartVaultPiece.H + 2 && dx * dx + dz * dz < (HeartVaultPiece.R - 0.5) * (HeartVaultPiece.R - 0.5)
    }

    fun inKennel(pos: Vec3d): Boolean {
        val c = center() ?: return false
        val dx = pos.x - c.x
        val dz = pos.z - c.z
        val dy = pos.y - HeartVaultPiece.FLOOR
        // under the balcony in the north, from the portcullis to the back wall
        return abs(dx - 0.5) < HeartVaultPiece.KENNEL_HALF + 1.5 && dz > HeartVaultPiece.KENNEL_MIN_DZ - 1.0 && dz < HeartVaultPiece.GATE_Z + 1.0 && dy > -2 && dy < 10
    }

    fun inArena(pos: Vec3d): Boolean = inDome(pos) || inKennel(pos)

    /** Horizontal distance from the centre. */
    fun radius(pos: Vec3d): Double {
        val m = mid()
        val dx = pos.x - m.x
        val dz = pos.z - m.z
        return sqrt(dx * dx + dz * dz)
    }

    /** Keeps a position on the fighting floor (inside the stands). */
    fun clampToFloor(pos: Vec3d, margin: Double = 2.5): Vec3d {
        val m = mid()
        val dx = pos.x - m.x
        val dz = pos.z - m.z
        val r = sqrt(dx * dx + dz * dz)
        val max = HeartVaultPiece.FIGHT_R - margin
        if (r <= max) return pos
        return Vec3d(m.x + dx / r * max, pos.y, m.z + dz / r * max)
    }

    // ------------------------------------------------------------------------------------- protection

    @JvmStatic
    fun isProtected(world: World, pos: BlockPos): Boolean {
        if (world.registryKey != World.NETHER) return false
        val c = center() ?: return false
        if (abs(pos.x - c.x) > 80 || abs(pos.z - c.z) > 90) return false
        return HeartVaultPiece.occupied(c, pos.x, pos.y, pos.z, 1)
    }

    fun init() {
        PlayerBlockBreakEvents.BEFORE.register { world, player, pos, _, _ ->
            if (player.isCreative || !isProtected(world, pos)) true
            else {
                player.sendMessage(Text.translatable("boss.hha_blood.protected").formatted(Formatting.DARK_RED), true)
                false
            }
        }
        UseBlockCallback.EVENT.register { player, world, hand, hit ->
            if (world.isClient || player.isCreative) return@register ActionResult.PASS
            val item = player.getStackInHand(hand).item
            val placing = item is BlockItem || item is BucketItem
            if (placing && (isProtected(world, hit.blockPos) || isProtected(world, hit.blockPos.offset(hit.side)))) {
                player.sendMessage(Text.translatable("boss.hha_blood.protected").formatted(Formatting.DARK_RED), true)
                ActionResult.FAIL
            } else ActionResult.PASS
        }
        UseItemCallback.EVENT.register { player, world, hand ->
            if (!world.isClient && !player.isCreative && player.getStackInHand(hand).item is BucketItem && isProtected(world, player.blockPos)) {
                ActionResult.FAIL
            } else ActionResult.PASS
        }
    }

    // ------------------------------------------------------------------------------------- temporary changes

    private const val SET_FLAGS = Block.NOTIFY_LISTENERS or Block.FORCE_STATE or Block.SKIP_DROPS

    fun designAt(pos: BlockPos): BlockState? {
        val c = center() ?: return null
        return HeartVaultPiece.design(pos.x - c.x, pos.y - HeartVaultPiece.FLOOR, pos.z - c.z)
    }

    /** Changes an arena block for the fight; it is put back by [restore]. */
    fun setTemp(world: ServerWorld, pos: BlockPos, state: BlockState) {
        val st = state(world.server!!)
        if (st.changed.add(pos.asLong())) st.markDirty()
        world.setBlockState(pos, state, SET_FLAGS)
    }

    /** Puts back every block the fight changed. */
    fun restore(world: ServerWorld) {
        val st = state(world.server!!)
        if (st.changed.isEmpty()) return
        val pos = BlockPos.Mutable()
        var n = 0
        for (l in st.changed) {
            pos.set(l)
            if (!ready(world, pos.x shr 4, pos.z shr 4)) continue
            world.setBlockState(pos, designAt(pos) ?: Blocks.AIR.defaultState, SET_FLAGS)
            n++
        }
        HhaBlood.LOGGER.info("Slaughter Pit: restored {} changed blocks", n)
        st.changed.clear()
        st.markDirty()
    }

    // ------------------------------------------------------------------------------------- portcullis

    /** The portcullis under the balcony: a plane at dz = GATE_Z, |dx| <= GATE_HALF. */
    private fun gatePos(dx: Int, dy: Int): BlockPos {
        val c = center()!!
        return BlockPos(c.x + dx, HeartVaultPiece.FLOOR + dy, c.z + HeartVaultPiece.GATE_Z)
    }

    /** Raises the portcullis by one row per call (bottom rows first, as if it slides up); true when open. */
    fun openGateStep(world: ServerWorld, row: Int): Boolean {
        if (center() == null) return true
        if (row > HeartVaultPiece.GATE_TOP) return true
        for (dx in -HeartVaultPiece.GATE_HALF..HeartVaultPiece.GATE_HALF) {
            val p = gatePos(dx, row)
            if (world.getBlockState(p).isOf(Blocks.IRON_BARS)) setTemp(world, p, Blocks.AIR.defaultState)
        }
        return row >= HeartVaultPiece.GATE_TOP
    }

    fun openGate(world: ServerWorld) {
        for (row in 0..HeartVaultPiece.GATE_TOP) openGateStep(world, row)
    }

    fun closeGate(world: ServerWorld) {
        if (center() == null) return
        for (dy in 0..HeartVaultPiece.GATE_TOP) for (dx in -HeartVaultPiece.GATE_HALF..HeartVaultPiece.GATE_HALF) {
            world.setBlockState(gatePos(dx, dy), HeartVaultPiece.BARS, SET_FLAGS)
        }
    }

    // ------------------------------------------------------------------------------------- pillars

    /** Smashes the lower part of a pillar around [at] (the Minotaur charged into it). Returns broken blocks. */
    fun smashPillar(world: ServerWorld, at: Vec3d, radius: Double): Int {
        val c = center() ?: return 0
        var n = 0
        val r = radius.toInt() + 1
        val base = BlockPos.ofFloored(at)
        val pos = BlockPos.Mutable()
        for (x in -r..r) for (y in 0..(radius * 1.6).toInt() + 1) for (z in -r..r) {
            pos.set(base.x + x, HeartVaultPiece.FLOOR + y, base.z + z)
            val d = Vec3d.ofCenter(pos).squaredDistanceTo(Vec3d(at.x, HeartVaultPiece.FLOOR + 1.5, at.z))
            if (d > radius * radius * (if (y <= 2) 1.3 else 0.8)) continue
            if (HeartVaultPiece.pillarAt((pos.x - c.x).toDouble(), (pos.z - c.z).toDouble(), 0.9) < 0) continue
            val st = world.getBlockState(pos)
            if (st.isAir) continue
            world.spawnParticles(net.minecraft.particle.BlockStateParticleEffect(net.minecraft.particle.ParticleTypes.BLOCK, st),
                pos.x + 0.5, pos.y + 0.5, pos.z + 0.5, 6, 0.4, 0.4, 0.4, 0.2)
            setTemp(world, pos.toImmutable(), Blocks.AIR.defaultState)
            n++
        }
        return n
    }

    // ------------------------------------------------------------------------------------- labyrinth walls

    /** A wall segment that rises out of the floor (positions on the floor, height [height]). */
    class RisingWall(val columns: List<BlockPos>, val height: Int, var level: Int = 0, var life: Int)

    /** Positions for labyrinth wall arcs in the middle ring (avoiding pillars, the altar and the players' feet). */
    fun labyrinthColumns(world: ServerWorld, seed: Int, avoid: List<Vec3d>): List<BlockPos> {
        val c = center() ?: return emptyList()
        val out = ArrayList<BlockPos>()
        val rng = java.util.Random(seed.toLong())
        // three arcs on two rings + two radial walls, each with a gap
        val rings = listOf(13.0, 22.0, 29.0)
        for ((ri, rr) in rings.withIndex()) {
            val start = rng.nextDouble() * Math.PI * 2
            val span = Math.PI * (1.1 + rng.nextDouble() * 0.5)
            val steps = (rr * span).toInt()
            for (s in 0..steps) {
                val a = start + span * s / steps
                val x = c.x + (Math.cos(a) * rr).toInt()
                val z = c.z + (Math.sin(a) * rr).toInt()
                out += BlockPos(x, HeartVaultPiece.FLOOR, z)
            }
            if (ri < 2) {
                val a = start + span + 0.3
                for (k in rr.toInt()..rings[ri + 1].toInt()) out += BlockPos(c.x + (Math.cos(a) * k).toInt(), HeartVaultPiece.FLOOR, c.z + (Math.sin(a) * k).toInt())
            }
        }
        return out.distinct().filter { p ->
            val dx = (p.x - c.x).toDouble()
            val dz = (p.z - c.z).toDouble()
            HeartVaultPiece.pillarAt(dx, dz, 1.5) < 0 &&
                avoid.none { it.squaredDistanceTo(p.x + 0.5, it.y, p.z + 0.5) < 2.5 * 2.5 } &&
                world.getBlockState(p).isAir
        }
    }

    /** Raises a wall by one layer; true when it is complete. */
    fun riseStep(world: ServerWorld, wall: RisingWall): Boolean {
        if (wall.level >= wall.height) return true
        val state = if (wall.level == wall.height - 1) dev.henny.hha_blood.hollows.HollowsBlocks.CHISELED_BLOOD_STONE.defaultState
            else dev.henny.hha_blood.hollows.HollowsBlocks.BLOOD_STONE_BRICKS.defaultState
        for (col in wall.columns) {
            val p = col.up(wall.level)
            val now = world.getBlockState(p)
            if (now.isAir || now.isOf(Blocks.FIRE)) setTemp(world, p, state)
        }
        wall.level++
        return wall.level >= wall.height
    }

    /** Lowers a wall by one layer (top first); true when it is gone. */
    fun sinkStep(world: ServerWorld, wall: RisingWall): Boolean {
        if (wall.level <= 0) return true
        wall.level--
        for (col in wall.columns) {
            val p = col.up(wall.level)
            if (designAt(p)?.isAir == true && !world.getBlockState(p).isAir) setTemp(world, p, Blocks.AIR.defaultState)
        }
        return wall.level <= 0
    }

    /** Breaks raised wall blocks around [at] (the Minotaur charges through). Returns the number of blocks. */
    fun smashWalls(world: ServerWorld, at: Vec3d, radius: Double): Int {
        var n = 0
        val base = BlockPos.ofFloored(at)
        val r = radius.toInt() + 1
        val pos = BlockPos.Mutable()
        for (x in -r..r) for (y in 0..4) for (z in -r..r) {
            pos.set(base.x + x, HeartVaultPiece.FLOOR + y, base.z + z)
            if (Vec3d.ofCenter(pos).squaredDistanceTo(at.x, pos.y + 0.5, at.z) > radius * radius) continue
            if (designAt(pos)?.isAir != true) continue
            val st = world.getBlockState(pos)
            if (st.isAir || st.isOf(Blocks.FIRE)) continue
            world.spawnParticles(net.minecraft.particle.BlockStateParticleEffect(net.minecraft.particle.ParticleTypes.BLOCK, st),
                pos.x + 0.5, pos.y + 0.5, pos.z + 0.5, 5, 0.4, 0.4, 0.4, 0.2)
            setTemp(world, pos.toImmutable(), Blocks.AIR.defaultState)
            n++
        }
        return n
    }

    // ------------------------------------------------------------------------------------- upgrade of old arenas

    private var upgradeJob: Iterator<Pair<Int, Int>>? = null
    private var checked = false
    private var upgradeColumns = 0

    /** Called every second while players are near: checks once per server run if the arena matches the design. */
    fun checkUpgrade(world: ServerWorld) {
        if (checked) return
        val c = center() ?: return
        // every chunk of the arena must be loaded for the check
        for (cx in ((c.x - 70) shr 4)..((c.x + 70) shr 4)) for (cz in ((c.z - 70) shr 4)..((c.z + 70) shr 4)) {
            if (!ready(world, cx, cz)) return
        }
        checked = true
        var total = 0
        var same = 0
        val pos = BlockPos.Mutable()
        val rng = java.util.Random(4711)
        var tries = 0
        while (total < 400 && tries < 20000) {
            tries++
            val dx = rng.nextInt(141) - 70
            val dz = rng.nextInt(141) - 70
            val dy = rng.nextInt(24) - 1
            if (!HeartVaultPiece.columnUsed(dx, dz)) continue
            val want = HeartVaultPiece.design(dx, dy, dz) ?: continue
            pos.set(c.x + dx, HeartVaultPiece.FLOOR + dy, c.z + dz)
            if (st(world, pos).block == want.block) same++
            total++
        }
        val ratio = if (total == 0) 1.0 else same.toDouble() / total
        // signature blocks that only the current design has (pillars, stands, kennel, balcony, labyrinth heart)
        val sig = ArrayList<Triple<Int, Int, Int>>()
        for (p in HeartVaultPiece.PILLARS) sig += Triple(p.x.toInt(), 3, p.z.toInt())
        for (k in 0 until 8) {
            val a = Math.toRadians(30.0 + k * 45.0)
            sig += Triple((Math.cos(a) * 42.5).toInt(), 1, (Math.sin(a) * 42.5).toInt())
        }
        sig += Triple(0, -1, 0); sig += Triple(0, 11, -36)
        // the kennel under the balcony (air, floor, portcullis) and the sealed old west kennel
        sig += Triple(0, 3, -47); sig += Triple(0, -1, -47); sig += Triple(0, 2, -33); sig += Triple(-55, 3, 0)
        // round "Biom + Arena cooler": the heart anchor, two gallery lamps, the titan skull
        sig += HeartVaultPiece.NEW_SIGNATURES
        var wrong = 0
        for ((dx, dy, dz) in sig) {
            val want = HeartVaultPiece.design(dx, dy, dz) ?: continue
            pos.set(c.x + dx, HeartVaultPiece.FLOOR + dy, c.z + dz)
            if (st(world, pos).block != want.block) {
                wrong++
                if (wrong <= 4) HhaBlood.LOGGER.info("Slaughter Pit: at {} {} {} found {} instead of {}", dx, dy, dz, st(world, pos).block, want.block)
            }
        }
        HhaBlood.LOGGER.info("Slaughter Pit: design check {}/{} random blocks match ({}), {}/{} signature blocks wrong",
            same, total, "%.2f".format(ratio), wrong, sig.size)
        if (ratio < 0.97 || wrong >= 3) startUpgrade()
    }

    private fun st(world: ServerWorld, pos: BlockPos): BlockState = world.getBlockState(pos)

    /** Chunk completely generated and loaded (isChunkLoaded is already true while it is still generating). */
    fun ready(world: ServerWorld, cx: Int, cz: Int): Boolean = world.chunkManager.getWorldChunk(cx, cz) != null

    private fun startUpgrade() {
        val cols = ArrayList<Pair<Int, Int>>()
        for (dx in -70..70) for (dz in -70..70) if (HeartVaultPiece.columnUsed(dx, dz)) cols += dx to dz
        upgradeColumns = cols.size
        upgradeJob = cols.iterator()
        HhaBlood.LOGGER.info("Slaughter Pit: the arena was built by an older version - rebuilding {} columns", cols.size)
    }

    fun upgrading(): Boolean = upgradeJob != null

    /** The design check ran and no rebuild is pending. */
    fun settled(): Boolean = checked && upgradeJob == null

    /** Rebuilds a slice of the arena per tick (old arenas from v0.4 - v0.6). */
    fun tickUpgrade(world: ServerWorld) {
        val job = upgradeJob ?: return
        val c = center() ?: run { upgradeJob = null; return }
        val pos = BlockPos.Mutable()
        var n = 0
        while (job.hasNext() && n < 350) {
            val (dx, dz) = job.next()
            n++
            for (y in (HeartVaultPiece.FLOOR - 7)..HeartVaultPiece.TOP_Y) {
                val want = HeartVaultPiece.design(dx, y - HeartVaultPiece.FLOOR, dz) ?: continue
                pos.set(c.x + dx, y, c.z + dz)
                if (world.getBlockState(pos) != want) world.setBlockState(pos, want, SET_FLAGS)
            }
        }
        if (!job.hasNext()) {
            upgradeJob = null
            // old blood-lake leftovers are fluid sources: the new design replaced them above
            HhaBlood.LOGGER.info("Slaughter Pit: rebuild finished ({} columns)", upgradeColumns)
        }
    }

    /** Debug: rebuild now, no matter what the check says. */
    fun forceRebuild() { checked = true; startUpgrade() }

    fun resetSession() { checked = false; upgradeJob = null }
}
